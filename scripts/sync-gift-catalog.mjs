import { readFile, writeFile } from 'node:fs/promises'
import { stripTypeScriptTypes } from 'node:module'
const source = await readFile(new URL('../src/data/gifts.ts', import.meta.url), 'utf8')
const { gifts } = await import(`data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(source)).toString('base64')}`)
const ids = gifts.map(gift => `('${gift.id.replaceAll("'", "''")}')`).join(',\n  ')
await writeFile(new URL('../supabase/seed.sql', import.meta.url), `-- Generated by node scripts/sync-gift-catalog.mjs. Does not remove existing claims.\ninsert into merrylist_private.gift_catalog (id) values\n  ${ids}\non conflict (id) do nothing;\n`)
console.log(`Prepared ${gifts.length} gift IDs for the shared database.`)
